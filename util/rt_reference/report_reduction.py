"""Render saved reduction evidence as a reproducible Markdown report."""

import argparse
import json
import os
import re
from pathlib import Path


def report_quick(results, source, output):
    raw_link = os.path.relpath(source.resolve(), output.resolve().parent)
    cpu = re.search(r"Model name:\s+(.+)", results["machine"]["lscpu"])[1]
    timing_rows, model_rows, sample_rows = [], [], []
    for group in results["groups"]:
        cores = group["accelerator_cores"]
        queues = cores + 1
        serial = next(run for run in group["runs"] if run["queues"] == 1)
        parallel = next(
            run for run in group["runs"] if run["queues"] == queues
        )
        assert serial["batch_ticks"] == parallel["batch_ticks"]
        assert serial["final_tick"] == parallel["final_tick"]
        simulation = group["median_simulation_wall_seconds"]
        process = group["median_process_wall_seconds"]
        timing_rows.append(
            f"| {cores} | 1 / {queues} | {simulation['1']:.6f} | "
            f"{simulation[str(queues)]:.6f} | {group['pdes_speedup']:.3f}x | "
            f"{process['1']:.6f} | {process[str(queues)]:.6f} | "
            f"{group['process_speedup']:.3f}x |"
        )
        compared = group["comparisons"][0]
        model_rows.append(
            f"| {cores} | {group['input_bytes'] // (1 << 20)} | "
            f"{serial['batch_ticks'] / 1000:,.0f} | "
            f"{serial['aggregate_input_bytes_per_batch_cycle']:.3f} | "
            f"{cores * (1 << 18):,}.0f | "
            f"{compared['simulated_counters_compared']:,} |"
        )
        for run in group["runs"]:
            sample_rows.append(
                f"| {cores} | {run['queues']} | {run['run_name']} | "
                f"{run['batch_start_tick']:,.0f} | "
                f"{run['batch_end_tick']:,.0f} | {run['final_tick']:,.0f} |"
            )
    hashes = results["artifact_sha256"]
    binary_hash = next(
        value for name, value in hashes.items() if name.endswith("gem5.opt")
    )
    firmware_hashes = {
        Path(name).name: value
        for name, value in hashes.items()
        if name.endswith(".elf")
    }
    repeats = len(results["groups"][0]["comparisons"])
    return f"""# Reduction experiment results: five-cycle DES versus PDES

Measured at `{results['measured_at_utc']}`. Generated by
`report_reduction.py` from [raw evidence]({raw_link}). The evidence records
every command, sample, executable/firmware/source hash and correctness check.
Untraced timing pairs per accelerator count: **{repeats}**, executed
sequentially. Table times are medians of those samples;
with one pair they are single measurements, not a wall-time trend.

Each accelerator reduces a distinct **1 MiB** region of binary32 `1.0f`:
8 accelerators process 8 MiB; 16 process 16 MiB. The boot image initializes
16 MiB before simulation; the eight-core case uses the first half. DES puts
all objects on one event queue. PDES uses one host queue plus one queue per
accelerator: 9 queues for eight accelerators, 17 for sixteen.

Request and response links are each **five cycles (5 ns)** at the **1 GHz
CPU/device clock**. The automatically derived quantum is **5 ns = 5,000
ticks** with a 1 ps tick period. The harness checked every instantiated
wrapper delay and `Root.sim_quantum` in both queue modes.

Both configurations use scalar `RiscvO3CPU` cores, private 8 KiB / 2-way L1I
and 16 KiB / 4-way L1D caches, 64 KiB Code TCM, 192 KiB Data TCM, 4 GHz
64-byte crossbars and 512 DMA/transport credits. Shared RAM has **four
controllers**, each at **32 GiB/s nominal bandwidth** and **100 ns service
latency**, interleaved at 64-byte boundaries. The complete configuration and
measurement boundaries are described in [REDUCTION.md](REDUCTION.md).

| Accelerators | DES / PDES queues | DES simulation (s) | PDES simulation (s) | Simulation speedup | DES process (s) | PDES process (s) | Process speedup |
| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |
{chr(10).join(timing_rows)}

Speedup is DES wall time divided by PDES wall time. Values below 1 mean
PDES was slower. Simulation timing starts after instantiation and ends when
`simulate()` returns; it includes boot, reduction, validation and export.
Process timing additionally includes Python/image setup, instantiation,
automatic exit statistics and cleanup. Runs have no transaction tracing.

| Accelerators | Processed MiB | Batch cycles, both modes | Input B/cycle | Final sum, both modes | Matching simulated counters |
| --- | ---: | ---: | ---: | ---: | ---: |
{chr(10).join(model_rows)}

Every partial sum is **262,144.0f**. Firmware checks each partial and the
final sum before exporting results. The harness checks descriptors, all
partial sums, final sums, per-controller traffic, queue placement, clocks,
cache configuration and DMA counters. DES and PDES outputs and all compared
simulated statistics across both dumps agree exactly; batch boundaries and
final simulation ticks also agree. Host runtime/process-memory counters are
excluded. This quick evaluation does not rerun the traced protocol, fault,
bandwidth-sensitivity or sustained-DMA-throughput suites.

| Accelerators | Queues | Sample | Batch start (ticks) | Batch end (ticks) | Final tick |
| --- | ---: | --- | ---: | ---: | ---: |
{chr(10).join(sample_rows)}

Host: **{cpu}**, `{results['machine']['hostname']}`.
Platform: `{results['machine']['platform']}`. Allowed CPU affinity:
`{','.join(map(str, results['machine']['cpu_affinity']))}`.
The harness checked for competing gem5 processes before, during and after
every timed run. OS scheduling, other host work and frequency variation can
still affect these single samples.

Reproduce from the repository root with a fresh output directory:

```sh
make -C util/rt_reference reduction
python3 util/rt_reference/validate_reduction.py --quick --runs={repeats} \\
    --output=m5out/reduction-5ns-quick
python3 util/rt_reference/report_reduction.py \\
    m5out/reduction-5ns-quick/results.json --output=/tmp/REDUCTION_RESULTS.md
```

The evaluation reused `build/RISCV/gem5.opt` and rebuilt reduction firmware.
Executable SHA-256:
`{binary_hash}`.
Host firmware SHA-256:
`{firmware_hashes['reduction-host.elf']}`.
Accelerator firmware SHA-256:
`{firmware_hashes['reduction-accelerator.elf']}`.
Base commit: `{results['git_commit']}`.
The raw evidence records hashes of the modified sources used for these runs.

[Historical full-suite evidence](REDUCTION_RESULTS.json) used 100 ns links
and quantum. Its timings and speedup do not describe this configuration.
"""


def report(results, source, output):
    if results.get("evaluation") == "quick-reduction":
        return report_quick(results, source, output)
    raw_link = os.path.relpath(source.resolve(), output.resolve().parent)
    runs = {run["run_name"]: run for run in results["runs"]}
    serial = runs["correctness-q1"]
    parallel = runs["correctness-q17"]
    assert serial["batch_ticks"] == parallel["batch_ticks"]
    assert serial["final_tick"] == parallel["final_tick"]
    probe = runs["throughput"]
    cpu = re.search(r"Model name:\s+(.+)", results["machine"]["lscpu"])[1]
    timing = sorted(
        name
        for name in runs
        if name.startswith("timing-") and name.endswith("-q1")
    )
    rows = []
    for name in timing:
        a, b = runs[name], runs[name.replace("-q1", "-q17")]
        seconds_a, seconds_b = (
            run["simulation_wall"]["wall_seconds"] for run in (a, b)
        )
        rows.append(
            f"| {name.split('-')[1]} | {seconds_a:.6f} | {seconds_b:.6f} | "
            f"{seconds_a / seconds_b:.3f} |"
        )
    medians = results["median_simulation_wall_seconds"]
    process = results["median_process_wall_seconds"]
    measurements = []
    for label, key, divisor in (
        ("Batch start (ticks)", "batch_start_tick", 1),
        ("Batch end (ticks)", "batch_end_tick", 1),
        ("Batch elapsed (1 GHz cycles)", "batch_ticks", 1000),
        ("Final simulation tick", "final_tick", 1),
    ):
        measurements.append(
            f"| {label} | {serial[key] / divisor:.0f} | "
            f"{parallel[key] / divisor:.0f} |"
        )
    for label, values in (
        ("Median simulation wall time (s)", medians),
        ("Median whole-process wall time (s)", process),
    ):
        measurements.append(
            f"| {label} | {values['1']:.6f} | {values['17']:.6f} |"
        )
    compared = next(
        pair
        for pair in results["comparisons"]
        if pair["left"] == "correctness-q1"
        and pair["right"] == "correctness-q17"
    )
    assert "trace_sha256" in compared and len(compared["trace_sha256"]) == 33
    fault = runs["fault-q1"]["wire"]
    dma = probe["dma"][0]
    wire = probe["wire"][0]
    return f"""# Reduction experiment results

Generated from `{source}`
by `report_reduction.py`. Configuration, commands,
measurement boundaries and test coverage are in [REDUCTION.md](REDUCTION.md).
The [raw JSON]({raw_link}) contains all samples, source/artifact
hashes, exact commands, machine information and statistic/trace comparisons.
Traced runs are excluded from speedup calculations.

Shared RAM latency is 100 cycles of the 1 GHz system clock (100 ns).
The reduction uses 32 GiB/s shared RAM; the bandwidth diagnostic and
single-accelerator DMA probe use 64 GiB/s.

The 16 partial sums are all **262,144.0f** and the host sum is
**4,194,304.0f**, in both queue modes. Python initialized the complete 16 MiB
input before simulation. Each accelerator DMA-read one distinct 1 MiB region.

| Measurement | One queue | Seventeen queues |
| --- | ---: | ---: |
{chr(10).join(measurements)}

**PDES speedup: {results['pdes_speedup']:.3f}×**, using one-queue median
simulation wall time divided by seventeen-queue median simulation wall time.
The separate whole-process speedup is **{results['process_speedup']:.3f}×**.
Simulation timing covers tick zero through firmware exit, after instantiation;
process timing also includes Python setup, image creation and instantiation.
The automatic exit statistics dump and cleanup are included only in process
timing; the explicit batch dump is included in simulation timing.
The batch statistics cover submission through final status checks, before host
sum validation/export. These are distinct, explicitly named boundaries.

| Untraced pair | One queue (s) | Seventeen queues (s) | Speedup |
| --- | ---: | ---: | ---: |
{chr(10).join(rows)}

There is **no simulated timing difference**: all
{compared['simulated_counters_compared']:,} simulated statistics across both
dumps agree, and all 33 complete transaction traces are byte-identical,
including payloads, timestamps, retries, ordering and MSI visibility.
Differences are confined to host runtime/process-memory metrics, which the
validator explicitly excludes from model-time comparison. Each untraced pair
also agrees with the traced reference for all simulated statistics and outputs.

The batch processes the 16 MiB at
**{serial['aggregate_input_bytes_per_batch_cycle']:.3f} input bytes/system
cycle** including host submission and completion overhead. Doubling shared
memory bandwidth, while keeping latency, clocks, firmware and queue mode
fixed, improves modeled completion by
**{results['bandwidth_doubling_completion_speedup']:.3f}×**. This confirms
sensitivity to the shared memory bottleneck; it does not imply the compute and
submission costs vanish.

The one-accelerator probe sustains
**{wire['read_sustained_bytes_per_cycle']:.3f} B/cycle reads** and
**{wire['write_sustained_bytes_per_cycle']:.3f} B/cycle
writes**, measured independently over the fixed central 512-packet windows.
At 1 GHz this is 64 GB/s (59.605 GiB/s) per direction. It reaches
{wire['peak_outstanding_reads']} outstanding reads and
{wire['peak_outstanding_writes']} outstanding writes in their respective
phases. Its command-average throughput, including descriptor transfer and
pipeline fill/drain, is **{dma['average_bytes_per_busy_cycle']:.3f} B/cycle**,
so the sustained window and whole-command average are reported separately.

Patterned unaligned copies, guard checks, forced read/write retries, four
invalid-command checks and recovery pass with matching one/two-queue traces
and statistics. The fault test has **{fault['error_responses']} error
responses**, with 64 requests in flight for each read/write failure. All
accepted errors drain before recovery and MSI; traces/statistics match.
A separate low-credit fault pair also passes with both ports under
backpressure, covering cancellation of owned packets and subsequent recovery.
The kernel uses {serial['code_tcm_bytes']:,} bytes of Code TCM and
{serial['data_tcm_bytes_including_stack']:,} bytes of Data TCM including its
16 KiB stack, within the 64/192 KiB capacities.

Host machine: **{cpu}**, `{results['machine']['hostname']}`.
Platform: `{results['machine']['platform']}`. Affinity permits CPUs
`{','.join(map(str, results['machine']['cpu_affinity']))}`. The harness checked
for other active gem5 processes before, during and after each run. Unrelated
host work, thermal state and OS scheduling can still affect wall-time samples.

The [validation notes](REDUCTION.md#validation-notes) document an earlier
O3 crash that subsequent debugger and sanitizer runs did not reproduce,
along with the scope and runtime suppression used for sanitizer checks.

Reproduce from the repository root:

```sh
make -C util/rt_reference reduction all backend-tests
scons build/RISCV/gem5.opt -j 8
python3 util/rt_reference/validate_reduction.py \\
    --output m5out/reduction --runs {len(timing)}
python3 util/rt_reference/report_reduction.py \\
    m5out/reduction/results.json --output /tmp/REDUCTION_RESULTS.md
```

Measured executable SHA-256:
`{results['gem5_sha256']}`.
Host firmware SHA-256:
`{results['firmware_sha256']['reduction-host.elf']}`.
Accelerator firmware SHA-256:
`{results['firmware_sha256']['reduction-accelerator.elf']}`.
Base commit: `{results['git_commit']}`.
The JSON also records the modified source hashes for this uncommitted worktree.
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(
        report(json.loads(args.results.read_text()), args.results, args.output)
    )


if __name__ == "__main__":
    main()
